#!/usr/bin/env bash

# エラー時に停止、未定義変数の参照で停止、パイプライン失敗検知
set -euo pipefail

# -----------------------------------------------------------------------------
# 定数・初期設定
# -----------------------------------------------------------------------------
readonly DOTFILES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
readonly BACKUP_DIR="$HOME/.dotfiles_backup/$(date +%Y%m%d_%H%M%S)"
readonly PROFILE_SH="$HOME/.dotfiles_profile.sh"
readonly PROFILE_LUA_DIR="$HOME/.config/dotfiles"
readonly PROFILE_LUA="$PROFILE_LUA_DIR/profile.lua"

# オプション用フラグ
DRY_RUN=false
ASSUME_YES=false

# プロファイル変数（ウィザードで決定）
SPEC="high"         # high | low
ENV_TYPE="local"    # local | cloud
HAS_NERD_FONT=true  # true | false
HAS_SUDO=false

# カラー設定
if [[ -t 1 ]]; then
    readonly C_RESET='\033[0m'
    readonly C_BOLD='\033[1m'
    readonly C_RED='\033[31m'
    readonly C_GREEN='\033[32m'
    readonly C_YELLOW='\033[33m'
    readonly C_BLUE='\033[34m'
    readonly C_CYAN='\033[36m'
else
    readonly C_RESET='' C_BOLD='' C_RED='' C_GREEN='' C_YELLOW='' C_BLUE='' C_CYAN=''
fi

log_info()    { echo -e "${C_BLUE}${C_BOLD}[INFO]${C_RESET} $*"; }
log_success() { echo -e "${C_GREEN}${C_BOLD}[OK]${C_RESET} $*"; }
log_warn()    { echo -e "${C_YELLOW}${C_BOLD}[WARN]${C_RESET} $*"; }
log_error()   { echo -e "${C_RED}${C_BOLD}[ERROR]${C_RESET} $*" >&2; }

prompt_confirm() {
    if [[ "$ASSUME_YES" == true ]]; then return 0; fi
    read -rp "$(echo -e "${C_CYAN}?${C_RESET} $1 [y/N]: ")" choice
    case "$choice" in
        [yY][eE][sS]|[yY]) return 0 ;;
        *) return 1 ;;
    esac
}

show_help() {
    cat << EOF
Usage: $(basename "$0") [OPTIONS]

Options:
    -d, --dry-run      変更を行わず、シミュレーション結果を表示
    -y, --yes          確認プロンプトをすべてスキップしてデフォルト値で実行
    -h, --help         このヘルプを表示
EOF
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            -d|--dry-run)  DRY_RUN=true; shift ;;
            -y|--yes)      ASSUME_YES=true; shift ;;
            -h|--help)     show_help; exit 0 ;;
            *) log_error "未知のオプション: $1"; show_help; exit 1 ;;
        esac
    done
}

detect_os() {
    case "$(uname -s)" in
        Darwin) echo "macos" ;;
        Linux)
            if grep -qi "microsoft" /proc/version 2>/dev/null; then
                echo "wsl"
            else
                echo "linux"
            fi
            ;;
        *) echo "unknown" ;;
    esac
}

# -----------------------------------------------------------------------------
# プロファイル設定ウィザード
# -----------------------------------------------------------------------------
configure_profile() {
    echo -e "\n${C_BOLD}=== 環境設定ウィザード ===${C_RESET}"

    # 1. sudo権限のチェック
    if command -v sudo >/dev/null 2>&1 && sudo -n true 2>/dev/null; then
        HAS_SUDO=true
    elif command -v sudo >/dev/null 2>&1; then
        HAS_SUDO=true # パスワード入力で使える可能性あり
    else
        HAS_SUDO=false
    fi

    if [[ "$ASSUME_YES" == true ]]; then
        log_info "デフォルトプロファイル (High / Local / NerdFont) を使用します。"
        return
    fi

    # 2. 環境種別 (Local / Cloud)
    local default_env="local"
    if [[ -n "${SSH_CONNECTION:-}" || -n "${SSH_CLIENT:-}" ]] || grep -q -i -E "docker|container" /proc/1/cgroup 2>/dev/null; then
        default_env="cloud"
    fi
    echo -e "${C_CYAN}?${C_RESET} 実行環境を選択してください:"
    echo "  1) ローカル (Desktop / Laptop) [デフォルト: $default_env がローカルなら1]"
    echo "  2) クラウド / リモート (SSH, VPS, DevContainer, rootless等)"
    read -rp "選択 [1-2] (default: 1): " env_choice
    case "$env_choice" in
        2) ENV_TYPE="cloud" ;;
        *) ENV_TYPE="local" ;;
    esac

    # 3. マシンスペック (High / Low)
    echo -e "\n${C_CYAN}?${C_RESET} マシンスペックを選択してください:"
    echo "  1) High (フル機能: LSP, Tree-sitter全機能, リッチUI)"
    echo "  2) Low  (軽量構成: Neo-tree自動起動なし, 余計なプラグインを停止して省メモリ化)"
    read -rp "選択 [1-2] (default: 1): " spec_choice
    case "$spec_choice" in
        2) SPEC="low" ;;
        *) SPEC="high" ;;
    esac

    # 4. フォント・アイコン対応
    echo -e "\n${C_CYAN}?${C_RESET} ターミナルで Nerd Fonts (アイコンフォント) は使用可能ですか？:"
    echo "  1) はい (アイコン・グリフ表示を有効化)"
    echo "  2) いいえ / 不明 (ASCII・テキスト表示へフォールバック)"
    read -rp "選択 [1-2] (default: 1): " font_choice
    case "$font_choice" in
        2) HAS_NERD_FONT=false ;;
        *) HAS_NERD_FONT=true ;;
    esac

    log_success "プロファイル決定: [Spec: $SPEC] [Env: $ENV_TYPE] [NerdFont: $HAS_NERD_FONT] [sudo: $HAS_SUDO]"
}

save_profile_files() {
    if [[ "$DRY_RUN" == true ]]; then
        log_info "[Dry-run] プロファイルファイルを生成予定: $PROFILE_SH, $PROFILE_LUA"
        return
    fi

    # Zsh / Shell 用プロファイル
    cat << EOF > "$PROFILE_SH"
# Auto-generated by dotfiles install.sh
export DOTFILES_SPEC="$SPEC"
export DOTFILES_ENV="$ENV_TYPE"
export DOTFILES_NERD_FONT=$HAS_NERD_FONT
export DOTFILES_HAS_SUDO=$HAS_SUDO
EOF
    log_success "シェル用プロファイルを生成しました: $PROFILE_SH"

    # Neovim (Lua) 用プロファイル
    mkdir -p "$PROFILE_LUA_DIR"
    cat << EOF > "$PROFILE_LUA"
-- Auto-generated by dotfiles install.sh
return {
  spec = "$SPEC",
  env = "$ENV_TYPE",
  has_nerd_font = $HAS_NERD_FONT,
  has_sudo = $HAS_SUDO,
}
EOF
    log_success "Neovim用プロファイルを生成しました: $PROFILE_LUA"
}

# -----------------------------------------------------------------------------
# シンボリックリンク
# -----------------------------------------------------------------------------
link_file() {
    local src="$1"
    local dest="$2"

    if [[ ! -e "$src" ]]; then
        log_warn "元ファイルが存在しません: $src (スキップ)"
        return
    fi

    if [[ -L "$dest" ]] && [[ "$(readlink "$dest")" == "$src" ]]; then
        log_success "すでにリンク済み: $dest -> $src"
        return
    fi

    if [[ -e "$dest" || -L "$dest" ]]; then
        if [[ "$DRY_RUN" == true ]]; then
            log_warn "[Dry-run] バックアップ予定: $dest -> $BACKUP_DIR"
        else
            mkdir -p "$BACKUP_DIR"
            mv "$dest" "$BACKUP_DIR/"
            log_warn "既存ファイルを退避しました: $dest -> $BACKUP_DIR/"
        fi
    fi

    if [[ "$DRY_RUN" == true ]]; then
        log_info "[Dry-run] リンク作成予定: $dest -> $src"
    else
        mkdir -p "$(dirname "$dest")"
        ln -snf "$src" "$dest"
        log_success "リンク作成完了: $dest -> $src"
    fi
}

setup_symlinks() {
    log_info "シンボリックリンクを作成します..."

    link_file "$DOTFILES_DIR/nvim" "$HOME/.config/nvim"

    # WezTermはローカル環境のみリンク（クラウド環境ではGUIターミナル不要）
    if [[ "$ENV_TYPE" == "local" ]]; then
        link_file "$DOTFILES_DIR/wezterm" "$HOME/.config/wezterm"
    fi

    link_file "$DOTFILES_DIR/.gitconfig" "$HOME/.gitconfig"
    [[ -f "$DOTFILES_DIR/.gitignore_global" ]] && link_file "$DOTFILES_DIR/.gitignore_global" "$HOME/.gitignore_global"

    link_file "$DOTFILES_DIR/zsh/.zshrc" "$HOME/.zshrc"
    [[ -f "$DOTFILES_DIR/zsh/.p10k.zsh" ]] && link_file "$DOTFILES_DIR/zsh/.p10k.zsh" "$HOME/.p10k.zsh"
}

# -----------------------------------------------------------------------------
# パッケージインストール
# -----------------------------------------------------------------------------
install_packages() {
    local os
    os="$(detect_os)"

    if [[ "$os" == "macos" ]]; then
        if ! command -v brew >/dev/null 2>&1; then
            if prompt_confirm "Homebrewをインストールしますか？"; then
                [[ "$DRY_RUN" == false ]] && /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
            fi
        fi
        if [[ -f "$DOTFILES_DIR/Brewfile" ]] && command -v brew >/dev/null 2>&1; then
            if prompt_confirm "Brewfile からパッケージをインストールしますか？"; then
                [[ "$DRY_RUN" == false ]] && brew bundle --file="$DOTFILES_DIR/Brewfile"
            fi
        fi

    elif [[ "$os" == "linux" || "$os" == "wsl" ]]; then
        if [[ "$HAS_SUDO" == false ]]; then
            log_warn "sudo権限が検知されなかったため、apt-get によるインストールをスキップします。"
            log_info "必要に応じて ~/bin や ~/.local/bin に手動でツールを配置してください。"
            return
        fi

        if command -v apt-get >/dev/null 2>&1; then
            if prompt_confirm "apt で主要ツールを更新・インストールしますか？"; then
                if [[ "$DRY_RUN" == false ]]; then
                    sudo apt-get update
                    sudo apt-get install -y git zsh curl ripgrep
                fi
            fi
        fi
    fi
}

# -----------------------------------------------------------------------------
# デフォルトシェル設定
# -----------------------------------------------------------------------------
setup_shell() {
    if ! command -v zsh >/dev/null 2>&1; then
        return
    fi
    if [[ "$HAS_SUDO" == false && "$ENV_TYPE" == "cloud" ]]; then
        log_info "クラウド/rootless環境のため chsh によるシェル変更をスキップします。"
        return
    fi

    local current_shell
    current_shell="$(basename "$SHELL")"
    if [[ "$current_shell" != "zsh" ]]; then
        if prompt_confirm "デフォルトシェルを zsh に変更しますか？"; then
            local zsh_path
            zsh_path="$(command -v zsh)"
            if [[ "$DRY_RUN" == false ]]; then
                chsh -s "$zsh_path" 2>/dev/null || log_warn "chsh に失敗しました。手動で設定してください。"
            fi
        fi
    fi
}

# -----------------------------------------------------------------------------
# メイン
# -----------------------------------------------------------------------------
main() {
    parse_args "$@"

    echo -e "${C_BOLD}=========================================${C_RESET}"
    echo -e "${C_BOLD}      Dotfiles Installer Starting        ${C_RESET}"
    echo -e "${C_BOLD}=========================================${C_RESET}"

    configure_profile
    save_profile_files
    install_packages
    setup_symlinks
    setup_shell

    echo -e "${C_BOLD}=========================================${C_RESET}"
    log_success "セットアップ完了！🎉"
}

main "$@"
